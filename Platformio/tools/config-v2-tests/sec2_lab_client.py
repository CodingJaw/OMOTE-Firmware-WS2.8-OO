#!/usr/bin/env python3
"""Manual ESP-IDF Security2 encrypted interoperability probe (LAB ONLY).

This is NOT a Home Assistant pairing client or a trusted device enrollment.
Requires a separately flashed, explicitly local-touch-enabled SEC2 LAB image.
Normal OMOTE firmware NEVER starts this listener. An opt-in LAB image has
an explicit on-device Settings > SEC2 encrypted LAB test button and separate
Start lab physical touch, but has no production credential/peer trust controls.
Run only on a backed-up, deliberately flashed test device.

Prerequisites:
  - Official ESP-IDF Python provisioning tools for compatible IDF release
  - IDF_PATH pointing at that ESP-IDF source tree, with Python dependencies
  - A six-digit PIN generated by the remote and displayed on its local screen

PIN is read interactively and is never passed on the command line, printed,
logged, or included in a URL.
"""
from __future__ import annotations

import argparse
import asyncio
from getpass import getpass
import ipaddress
import json
import os
from pathlib import Path
import re
import sys

from sec2_lab_ha_proof import make_candidate_proof, check_lab_reply


async def probe(host: str, port: int, *, ha_proof: bool = False) -> None:
    idf_path = Path(os.environ.get("IDF_PATH", "")).expanduser()
    if not idf_path.is_dir():
        raise RuntimeError("IDF_PATH must point to a local Espressif ESP-IDF checkout")
    for folder in (
        idf_path / "components/protocomm/python",
        idf_path / "tools/esp_prov",
    ):
        if not folder.is_dir():
            raise RuntimeError("Missing official ESP-IDF provisioning modules")
        sys.path.insert(0, str(folder))
    from security.security2 import Security2
    from transport.transport_http import Transport_HTTP

    # Transport_HTTP preserves the session cookie used by protocomm_httpd.
    # The transport runs on a deliberately separate, short-lived lab port.
    tp = Transport_HTTP(f"{host}:{port}")
    try:
        version = await tp.send_data("proto-ver", "-")
        try:
            metadata = json.loads(version)
            details = metadata["prov"]
            if (
                details["ver"] != "omote-sec2-lab-v1"
                or type(details["sec_patch_ver"]) is not int
                or details["sec_patch_ver"] != 1
            ):
                raise ValueError("Unexpected security version")
        except (TypeError, KeyError, ValueError) as exc:
            raise RuntimeError("Unrecognized lab protocol; refusing handshake") from exc

        pin = getpass("Enter the six-digit code shown on the remote: ")
        if not re.fullmatch(r"[0-9]{6}", pin):
            raise RuntimeError("A six-digit device-screen code is required")
        sec = Security2(
            sec_patch_ver=1, username="omote-ha",
            password=pin, verbose=False,
        )
        # Drop the extra named reference to the immutable user PIN string.
        pin = None
        response = None
        while True:
            request = sec.security_session(response)
            if request is None:
                break
            response = await tp.send_data("prov-session", request)
            if response is None:
                raise RuntimeError("Security2 handshake returned no response")

        encrypted = sec.encrypt_data(b"OMOTE-SEC2-PROBE-V1")
        reply = await tp.send_data("omote-probe", encrypted.decode("latin-1"))
        decrypted = sec.decrypt_data(reply.encode("latin-1"))
        if decrypted != b"OMOTE-SEC2-OK-V1":
            raise RuntimeError("Authenticated encrypted probe response mismatch")
        print("PASS: Security2 SRP6a session and AES-GCM encrypted probe.")
        if ha_proof:
            # The cookie was issued by the ESP-IDF Security2 HTTP transport.
            # Never trust it as an identity; use only as an additional
            # transcript/session binding for the ephemeral candidate proof.
            cookie = tp.headers.get("Cookie", "")
            proof = make_candidate_proof(cookie)
            ciphertext = sec.encrypt_data(proof)
            response = await tp.send_data("omote-ha-proof", ciphertext.decode("latin-1"))
            plaintext = sec.decrypt_data(response.encode("latin-1"))
            check_lab_reply(plaintext)
            print("PASS: ephemeral HA P-256 private-key possession proved inside encrypted session.")
        print("No permanent device/HA identity, pairing trust, or configuration writes were tested.")
    finally:
        tp.conn.close()


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--host", required=True, help="Lab Waveshare IPv4 address")
    ap.add_argument("--port", type=int, default=18082)
    ap.add_argument("--ha-proof", action="store_true",
                    help="Also verify ephemeral HA P-256 key possession (NOT trusted pairing)")
    ap.add_argument("--ack-lab-only", action="store_true",
                    help="Acknowledge this is NOT authenticated OMOTE pairing")
    args = ap.parse_args()
    if not args.ack_lab_only:
        ap.error("Use --ack-lab-only after verifying the local lab firmware and UI")
    try:
        ipaddress.IPv4Address(args.host)
    except ipaddress.AddressValueError as exc:
        ap.error("Use a literal IPv4 address for the lab device")
    if not 1 <= args.port <= 65535:
        ap.error("Invalid lab port")
    try:
        asyncio.run(probe(args.host, args.port, ha_proof=args.ha_proof))
    except Exception as exc:
        # Never print a remote response body, cryptographic secret or PIN.
        print(f"FAIL: interoperability probe aborted ({type(exc).__name__}).",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
